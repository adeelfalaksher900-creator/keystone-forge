import { useCallback, useEffect, useState } from 'react';
import { view } from '@forge/bridge';
import { Icon, Segmented, Skeleton, ago, call, useToast } from './ui.jsx';
import { Areas, Empty, Overview, People, WhatIf } from './views.jsx';
import { AreaSheet, PersonSheet } from './sheets.jsx';
import IssuePanel from './IssuePanel.jsx';

const TABS = [
  { value: 'overview', label: 'Overview' },
  { value: 'areas', label: 'Areas' },
  { value: 'people', label: 'People' },
  { value: 'whatif', label: 'What-if' },
];

export default function App() {
  const [ctx, setCtx] = useState(null);
  useEffect(() => { view.getContext().then(setCtx, () => setCtx({})); }, []);
  if (!ctx) return null;
  if (ctx.extension?.type === 'jira:issuePanel') return <IssuePanel ctx={ctx} />;
  return <Home />;
}

function Home() {
  const [boot, setBoot] = useState(null);
  const [projectKey, setProjectKey] = useState(null);
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);
  const [tab, setTab] = useState('overview');
  const [area, setArea] = useState(null);
  const [person, setPerson] = useState(null);
  const [toastEl, toast] = useToast();

  useEffect(() => {
    call('bootstrap').then((b) => { setBoot(b); setProjectKey(b.settings.defaultProject || 'SAMPLE'); }, (e) => setError(e.message));
  }, []);

  const load = useCallback(async (refresh = false) => {
    if (!projectKey) return;
    setLoading(true); setError(null);
    try {
      const d = await call('analysis', { projectKey, refresh });
      setData(d);
      setPerson((p) => (p ? d.people.find((x) => x.accountId === p.accountId) || null : null));
    } catch (e) { setError(e.message); } finally { setLoading(false); }
  }, [projectKey]);
  useEffect(() => { setData(null); load(); }, [load]);

  const pickProject = async (key) => {
    setProjectKey(key);
    call('setDefaultProject', { projectKey: key }).catch(() => {});
  };

  return (
    <main className="page">
      <div className="top">
        <div className="brand">
          <img src="./keystone.svg" alt="" />
          <div><div className="eyebrow">Knowledge risk radar</div><h1>Keystone</h1></div>
        </div>
        <div className="controls">
          {data?.sample && <span className="badge sample" title="Fictional team generated by Keystone so you can explore without real data">Sample data</span>}
          {data && !data.sample && <span className="faint">Updated {ago(data.cachedAt)} · {data.issueCount} items{data.truncated ? ' (newest 300)' : ''}</span>}
          <label className="sr" htmlFor="proj">Project</label>
          <select id="proj" className="select" value={projectKey || ''} onChange={(e) => pickProject(e.target.value)} disabled={!boot}>
            {boot?.projects.map((p) => <option key={p.key} value={p.key}>{p.name}{p.sample ? '' : ` (${p.key})`}</option>)}
          </select>
          <button className="btn" onClick={() => load(true)} disabled={loading || !projectKey} aria-label="Rescan project"><span className={loading ? 'spin' : ''} style={{ display: 'inline-flex' }}><Icon.refresh /></span>Rescan</button>
        </div>
      </div>

      <Segmented options={TABS} value={tab} onChange={setTab} label="Keystone views" />

      {error && (
        <div className="callout" style={{ '--c': 'var(--critical)' }} role="alert"><Icon.alert /><div className="grow"><b>Couldn’t load this project.</b> <span className="muted">{error}</span></div><button className="btn ghost" onClick={() => load(true)}>Retry</button></div>
      )}

      {!data && !error && (
        <div aria-busy="true" aria-label="Loading">
          <Skeleton h={112} />
          <div className="grid two" style={{ marginTop: 16 }}><Skeleton h={340} /><Skeleton h={340} /></div>
          {projectKey !== 'SAMPLE' && <p className="faint" style={{ textAlign: 'center', marginTop: 16 }}>Reading up to 300 work items, their history and comments…</p>}
        </div>
      )}

      {data && data.issueCount === 0 && (
        <section className="card"><Empty title="No recent work in this project" text="Keystone looks at work items updated in the last 12 months. Try another project, or explore the sample workspace to see what Keystone finds."
          action={<button className="btn primary" onClick={() => pickProject('SAMPLE')}>Explore sample workspace</button>} /></section>
      )}

      {data && data.issueCount > 0 && (
        <>
          {tab === 'overview' && <Overview data={data} openArea={setArea} openPerson={setPerson} />}
          {tab === 'areas' && <Areas data={data} openArea={setArea} />}
          {tab === 'people' && <People data={data} openPerson={setPerson} />}
          {tab === 'whatif' && <WhatIf data={data} projectKey={projectKey} openArea={setArea} />}
          <p className="faint" style={{ marginTop: 20, textAlign: 'center' }}>Ask the <b>Keystone</b> agent in Rovo “Who knows the most about…?”, or connect the Keystone MCP tools to your coding agent.</p>
        </>
      )}

      {area && <AreaSheet area={area} sample={data?.sample} onClose={() => setArea(null)} />}
      {person && <PersonSheet key={person.accountId} person={person} projectKey={projectKey} sample={data?.sample} me={boot?.accountId} onClose={() => setPerson(null)} onAvailability={() => load(false)} toast={toast} />}
      {toastEl}
    </main>
  );
}
